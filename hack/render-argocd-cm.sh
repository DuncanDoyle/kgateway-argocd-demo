#!/usr/bin/env bash
# Compiles the shared healthchecks/lua/<shape>/health.lua scripts into the two
# forms a user can install:
#
#   healthchecks/argocd-cm-patch.yaml      kubectl patch of argocd-cm
#   healthchecks/argocd-helm-values.yaml   argo-helm values, under configs.cm
#
# Both carry the SAME five Lua scripts; only the wrapper differs. Which one a
# user needs depends on how they manage argocd-cm: a kubectl patch is reverted
# the next time a declarative source (argo-helm, Kustomize, a GitOps repo) is
# applied, so anyone running the chart needs the values form instead.
#
# argocd-cm entries OVERRIDE bundled checks (util/lua/lua.go GetHealthScript:
# configmap exact -> configmap wildcard -> embedded exact -> embedded
# wildcard), so this works before the upstream PR merges AND remains a valid
# escape hatch afterwards.
set -euo pipefail

cd "$(dirname "$0")/.."
OUT_CM="healthchecks/argocd-cm-patch.yaml"
OUT_HELM="healthchecks/argocd-helm-values.yaml"
source ./hack/kind-shapes.sh

# emit_kind <kind> <shape> <key-indent> <lua-indent>
# The two outputs differ only in how deeply the key and its block scalar are
# nested, so one function serves both.
emit_kind() {
  local kind="$1" shape="$2" key_indent="$3" lua_indent="$4"
  printf '%s%s: |\n' "$key_indent" "resource.customizations.health.gateway.kgateway.dev_${kind}"
  sed "s/^/${lua_indent}/" "healthchecks/lua/${shape}/health.lua"
}

emit_all() {
  local key_indent="$1" lua_indent="$2"
  for kind in ${ANCESTORS_KINDS}; do emit_kind "$kind" ancestors "$key_indent" "$lua_indent"; done
  for kind in ${CONDITIONS_KINDS}; do emit_kind "$kind" conditions "$key_indent" "$lua_indent"; done
}

{
  cat <<'HEADER'
# GENERATED by hack/render-argocd-cm.sh — do not edit by hand.
# Apply with:
#   kubectl -n argocd patch configmap argocd-cm --patch-file healthchecks/argocd-cm-patch.yaml
#
# NOTE: a kubectl patch is reverted the next time a declarative source for
# argocd-cm is applied. If you run the argo-helm chart, use
# argocd-helm-values.yaml instead.
apiVersion: v1
kind: ConfigMap
metadata:
  name: argocd-cm
  namespace: argocd
data:
HEADER
  emit_all '  ' '    '
} > "${OUT_CM}"

{
  cat <<'HEADER'
# GENERATED by hack/render-argocd-cm.sh — do not edit by hand.
#
# argo-helm (argo-cd chart) values. Merge into your existing values file, or
# pass alongside it:
#   helm upgrade --install argo-cd argo/argo-cd -n argocd \
#     -f your-values.yaml -f argocd-helm-values.yaml
#
# Unlike a kubectl patch of argocd-cm, this survives the next chart upgrade,
# which is why it is the right form for anyone managing ArgoCD declaratively.
#
# The health entries below need no controller restart; ArgoCD reads argocd-cm
# live. Applications still cache per-resource health, so hard-refresh them once
# after the upgrade (docs/INSTALL.md explains).
#
# OPTIONAL -- only if you read health from kubectl rather than the UI. This
# makes the controller persist per-resource health onto
# Application.status.resources[]. It DOES restart the application controller.
# See "Why health does not show up in kubectl" in docs/INSTALL.md.
#
#   configs:
#     params:
#       controller.resource.health.persist: "true"
configs:
  cm:
HEADER
  emit_all '    ' '      '
} > "${OUT_HELM}"

echo "wrote ${OUT_CM}"
echo "wrote ${OUT_HELM}"
